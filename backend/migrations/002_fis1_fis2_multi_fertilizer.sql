-- Migrasi FIS-1 + FIS-2 dan rekomendasi multi-pupuk.
-- Jalankan setelah backup database dan pastikan aplikasi dihentikan.
-- DDL bersifat aditif: data rekomendasi lama tetap dipertahankan.

BEGIN;

ALTER TABLE public.rekomendasi
    ADD COLUMN IF NOT EXISTS algorithm_version VARCHAR(40) NOT NULL DEFAULT 'legacy',
    ADD COLUMN IF NOT EXISTS fuzzy_trace JSONB NOT NULL DEFAULT '{}'::jsonb,
    ADD COLUMN IF NOT EXISTS z_n DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS z_p DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS z_k DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS z_dolomit DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS z_belerang DOUBLE PRECISION;

-- Field lama tetap dipertahankan untuk rekaman historis satu-pupuk,
-- tetapi boleh NULL untuk header rekomendasi multi-pupuk yang baru.
ALTER TABLE public.rekomendasi
    ALTER COLUMN jenis_pupuk DROP NOT NULL,
    ALTER COLUMN dosis DROP NOT NULL,
    ALTER COLUMN kategori DROP NOT NULL;

CREATE TABLE IF NOT EXISTS public.rekomendasi_detail (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rekomendasi_id      INTEGER NOT NULL REFERENCES public.rekomendasi(id) ON DELETE CASCADE,
    kode_pupuk          VARCHAR(30) NOT NULL,
    nama_pupuk          VARCHAR(100) NOT NULL,
    dosis_g             INTEGER,
    dosis_min_g         INTEGER,
    dosis_maks_g        INTEGER,
    satuan              VARCHAR(20) NOT NULL DEFAULT 'g/pohon',
    kategori            VARCHAR(40) NOT NULL,
    direkomendasikan    BOOLEAN NOT NULL DEFAULT TRUE,
    catatan             VARCHAR(255),
    CONSTRAINT ck_rekomendasi_detail_dosis_nonnegative
        CHECK (
            (dosis_g IS NULL OR dosis_g >= 0)
            AND (dosis_min_g IS NULL OR dosis_min_g >= 0)
            AND (dosis_maks_g IS NULL OR dosis_maks_g >= 0)
            AND (dosis_min_g IS NULL OR dosis_maks_g IS NULL OR dosis_min_g <= dosis_maks_g)
        )
);

CREATE INDEX IF NOT EXISTS ix_rekomendasi_detail_rekomendasi_id
    ON public.rekomendasi_detail (rekomendasi_id);

CREATE INDEX IF NOT EXISTS ix_rekomendasi_algorithm_version
    ON public.rekomendasi (algorithm_version);

COMMIT;

